// Copies what the site's Daisy page needs from this folder into the site (modelled on
// sevenup-tiles/scripts/copy-to-site.mjs):
//   src/daisy/tiles.generated.js      both tiles' files, for the tile loader's memory loader, and the
//                                     memory house's fingerprint (the house version check)
//   src/daisy/published.generated.js  the published tiles, pinned (from published.json), or null
//   src/daisy/router.js               the page's routing (tested here: test/router.test.mjs)
//   src/daisy/record.js               the saved record and its check (test/record.test.mjs), with
//   src/daisy/shared/                 the dice and rules it re-checks a match with (verifyMatch)
//
// Usage:  node scripts/sync-shared.mjs
//         node scripts/copy-to-site.mjs C:\thunderbird-cafe\pyxorium.github.io
// Run it again whenever a tile, the routing or the record changes, and after publishing.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, TILES, fingerprint } from './tiles.mjs';

const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8' };
export const SHARED_FOR_RECORD = ['verify.js', 'dice.js', 'sha256.js', 'rules.js', 'tid.js'];

export function packTile(id) {
  const t = TILES[id];
  const resources = {};
  for (const f of t.files) {
    const entry = { src: readFileSync(join(ROOT, id, f), 'utf8'), 'content-type': TYPES[extname(f)] };
    resources[`/${f}`] = entry;
    if (f === 'index.html') resources['/'] = entry;
  }
  return { name: t.name, description: t.description, sizing: t.sizing, resources };
}

export function pinnedFrom(published) {
  if (!published || !published.house || !published.player) return null;
  const pin = (p) => ({ uri: p.uri, cid: p.cid });
  return { account: published.account, house: pin(published.house), player: pin(published.player) };
}

const COPY_NOTE = (from) => `// COPY of daisy-tiles/${from} (tested there: npm test). Edit it there, then run\n// node scripts/copy-to-site.mjs <site folder> to bring it here.\n\n`;

export function siteFiles(published = existsSync(join(ROOT, 'published.json')) ? JSON.parse(readFileSync(join(ROOT, 'published.json'), 'utf8')) : null) {
  const tiles = { house: packTile('house'), player: packTile('player') };
  const pinned = pinnedFrom(published);
  const files = {
    'tiles.generated.js': '// Generated by daisy-tiles/scripts/copy-to-site.mjs: both Daisy tiles, file by file, for the tile\n' +
      "// loader's memory loader, and the memory house's fingerprint (for the house version check). Don't edit;\n" +
      '// change the tiles in daisy-tiles and run the script again.\n\n' +
      `export const MEMORY_HOUSE_VERSION = ${JSON.stringify(fingerprint('house'))};\n\n` +
      `export const TILES = ${JSON.stringify(tiles, null, 1)};\n`,
    'published.generated.js': '// Generated by daisy-tiles/scripts/copy-to-site.mjs from published.json: the published Daisy tiles,\n' +
      '// pinned (address and record CID). The table loads exactly these; a changed record is refused.\n' +
      "// null means not published yet: the table uses its memory copies. Don't edit; publish and run the script.\n\n" +
      `export const PUBLISHED = ${JSON.stringify(pinned, null, 2)};\n`,
    'router.js': COPY_NOTE('page/router.js') + readFileSync(join(ROOT, 'page', 'router.js'), 'utf8'),
    'record.js': COPY_NOTE('page/record.js') + readFileSync(join(ROOT, 'page', 'record.js'), 'utf8').replace("from '../shared/verify.js'", "from './shared/verify.js'"),
  };
  for (const f of SHARED_FOR_RECORD) files[`shared/${f}`] = COPY_NOTE(`shared/${f}`) + readFileSync(join(ROOT, 'shared', f), 'utf8');
  return { files, pinned };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const site = process.argv[2];
  if (!site) { console.error('Usage: node scripts/copy-to-site.mjs <site folder>'); process.exit(1); }
  const out = join(site, 'src', 'daisy');
  mkdirSync(join(out, 'shared'), { recursive: true });
  const { files, pinned } = siteFiles();
  for (const [name, text] of Object.entries(files)) writeFileSync(join(out, name), text);
  console.log(`Wrote ${Object.keys(files).length} files to ${out}: the tiles, published.generated.js (${pinned ? 'pinned to the published tiles' : 'not published yet: the memory copies'}), router.js, record.js and shared/.`);
}
